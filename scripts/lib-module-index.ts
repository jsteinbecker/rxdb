/**
 * Regenerates `docs/lib-modules.md` from the module docs in `src/lib`: the
 * `@module` comment at the top of each TypeScript file and the `@component`
 * comment at the top of each Svelte component. The first paragraph of each
 * becomes its one-line summary.
 *
 * Usage: `npm run docs:lib`
 *
 * @module
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const LIB = join(ROOT, 'src/lib');
const OUT = join(ROOT, 'docs/lib-modules.md');

/** Folder descriptions, in the order the index lists them. */
const FOLDERS: [string, string][] = [
	['catalog', 'Browser-safe package contracts, interpretation, titles and read projections.'],
	[
		'labels',
		'Reading SPL labels: sections, ingredients, appearance, routes, reconstitution and dose-form corrections.'
	],
	[
		'medication',
		'Domain arithmetic and naming: strengths, quantities, rationals, ingredients, moieties and ions.'
	],
	[
		'formulary',
		'Formulary items, hierarchy grouping, equivalence groups and pharmacologic class rules.'
	],
	[
		'curation',
		'Human corrections: property overrides, citations, local superseding concepts and reinterpretation.'
	],
	['compounds', 'The compound builder.'],
	[
		'imprints',
		'Imprint Layout Notation (ILN): parsing, rendering, shapes, and conversion from SPL and photos.'
	],
	['client', 'Browser-only stores and helpers.'],
	['shared', 'Small utilities shared by every layer.'],
	['components', 'Svelte components.'],
	[
		'server',
		'Server-only code: providers, catalog persistence and sync, curation stores, media and infrastructure.'
	]
];

function walk(dir: string): string[] {
	return readdirSync(dir).flatMap((name) => {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) return walk(path);
		const source = /\.(ts|svelte)$/.test(name) && !/\.(test|d)\.ts$/.test(name);
		return source ? [path] : [];
	});
}

/** A doc comment's prose paragraphs, each joined onto one line; stops at the first tag, fence or table. */
function paragraphs(lines: string[]): string[] {
	const out: string[] = [];
	let current: string[] = [];
	for (const line of lines) {
		const text = line.trim();
		if (text.startsWith('@') || text.startsWith('```') || text.startsWith('|')) break;
		if (text) current.push(text);
		else if (current.length) (out.push(current.join(' ')), (current = []));
	}
	if (current.length) out.push(current.join(' '));
	return out;
}

/**
 * The summary of a doc comment: its first paragraph. A one-line title ("NDC
 * format plumbing.") is followed by the first sentence of the next paragraph.
 */
function firstParagraph(lines: string[]): string | null {
	const [first, second] = paragraphs(lines);
	if (!first) return null;
	const isTitle = first.length <= 80 && !/[.?!]\s/.test(first) && !first.includes(':');
	if (!isTitle || !second) return first;
	const sentence = /^.+?[.?!](?=\s|$)/.exec(second)?.[0] ?? second;
	return `${first.replace(/[.]$/, '')} — ${sentence}`;
}

function summaryOf(path: string): string | null {
	const source = readFileSync(path, 'utf8');
	if (path.endsWith('.svelte')) {
		const match = /^<!--\s*\n@component\n([\s\S]*?)-->/.exec(source);
		return match ? firstParagraph(match[1].split('\n')) : null;
	}
	const match = /^\s*\/\*\*([\s\S]*?)\*\//.exec(source);
	if (!match || !match[1].includes('@module')) return null;
	return firstParagraph(match[1].split('\n').map((line) => line.replace(/^\s*\* ?/, '')));
}

const byFolder = new Map<string, { file: string; summary: string | null }[]>();
for (const path of walk(LIB).sort()) {
	const rel = relative(LIB, path);
	if (rel === 'index.ts') continue;
	const top = rel.includes('/') ? rel.slice(0, rel.indexOf('/')) : '';
	const list = byFolder.get(top) ?? [];
	list.push({ file: rel, summary: summaryOf(path) });
	byFolder.set(top, list);
}

const lines: string[] = [
	'# Library module reference',
	'',
	'<!-- Generated by `npm run docs:lib` from the module docs in src/lib. Edit those, not this file. -->',
	'',
	'One line per module in `src/lib`, taken from the `@module` doc at the top of each TypeScript file and the `@component` doc at the top of each Svelte component. Hover a module or component in the editor for its full documentation. See [the library architecture](lib-architecture.md) for ownership and the rules between layers.',
	'',
	'## Documentation conventions',
	'',
	'- **Every module opens with a `/** … @module */` comment**: what it is for, the domain rules it encodes, and worked examples where the rule is subtle. The first paragraph is its summary here.',
	'- **Every Svelte component opens with an `<!-- @component … -->` comment**, shown when hovering the component where it is used, with a usage example where props are not obvious.',
	'- **Exports, props and type members carry `/** … */` docs**, never `//` comments, so editors show them at every use. Prop docs live on the props type. Defaults are stated with `@defaultValue`.',
	'- **`//` comments are for implementation notes** inside function bodies and markup, and for section dividers.',
	'- Long design rationale stays in the module doc next to the code it explains; cross-cutting rules live in `docs/` (for example [strength basis rules](strength-basis-rules.md) and [ILN](iln.md)).',
	''
];

const known = new Set(FOLDERS.map(([name]) => name));
const order = [
	...FOLDERS,
	...[...byFolder.keys()]
		.filter((key) => !known.has(key))
		.map((key) => [key, ''] as [string, string])
];
for (const [folder, description] of order) {
	const entries = byFolder.get(folder);
	if (!entries) continue;
	lines.push(`## ${folder || 'Top level'}`, '');
	if (description) lines.push(description, '');
	lines.push('| Module | Summary |', '| --- | --- |');
	for (const { file, summary } of entries) {
		const cell = (summary ?? '_Undocumented._').replace(/\|/g, '\\|');
		lines.push(`| [\`${file}\`](../src/lib/${file}) | ${cell} |`);
	}
	lines.push('');
}

writeFileSync(OUT, lines.join('\n'));
const missing = [...byFolder.values()].flat().filter((entry) => !entry.summary);
console.log(`Wrote ${relative(ROOT, OUT)}; ${missing.length} undocumented.`);
for (const { file } of missing) console.log(`  ${file}`);
